#!/usr/bin/env node
/**
 * build_invariant_context.js
 *
 * Writes {meta-dir}/invariant-context.md and {meta-dir}/scope-files.txt without
 * sending source through the model. The extract lists every matching line. It
 * does not sample, and it does not inline whole files — discovery agents read
 * the files in scope-files.txt themselves.
 *
 * Usage:
 *   node build_invariant_context.js <PROJECT_ROOT> [--meta-dir fizz_data] [--suite-dir test/fizz]
 */

const fs = require('fs');
const path = require('path');

const SKIP_DIRS = new Set([
    'node_modules', 'lib', 'out', 'cache', 'artifacts', 'broadcast',
    'coverage', 'typechain-types', 'typechain', '.git', 'x-ray',
]);

function readFoundrySrc(projectRoot) {
    const foundryToml = path.join(projectRoot, 'foundry.toml');
    if (!fs.existsSync(foundryToml)) return null;
    for (const rawLine of fs.readFileSync(foundryToml, 'utf8').split(/\r?\n/)) {
        const line = rawLine.trim();
        const match = line.match(/^src\s*=\s*"([^"]+)"/);
        if (match) return match[1];
    }
    return null;
}

function walkSol(dir, out) {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (SKIP_DIRS.has(entry.name)) continue;
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walkSol(full, out);
        else if (entry.isFile() && entry.name.endsWith('.sol')) out.push(full);
    }
}

function rel(projectRoot, file) {
    return path.relative(projectRoot, file).split(path.sep).join('/');
}

function protocolRoots(projectRoot) {
    const src = readFoundrySrc(projectRoot);
    const candidates = [];
    if (src) candidates.push(path.join(projectRoot, src));
    for (const name of ['src', 'contracts', 'script']) {
        const full = path.join(projectRoot, name);
        if (fs.existsSync(full) && !candidates.includes(full)) candidates.push(full);
    }
    return candidates;
}

function harnessFiles(projectRoot, suiteDir) {
    const root = path.join(projectRoot, suiteDir);
    const files = [];
    for (const name of ['Base.sol', 'Snapshots.sol', 'Properties.sol']) {
        const full = path.join(root, name);
        if (fs.existsSync(full)) files.push(full);
    }
    const handlers = path.join(root, 'handlers');
    if (fs.existsSync(handlers)) walkSol(handlers, files);
    return files;
}

const PATTERNS = [
    ['Aggregate-looking declarations', /\b(?:total|sum|accumulated|aggregate)[A-Za-z0-9_]*/],
    ['Conversion-looking functions', /function\s+\w*(?:convertTo|preview|toAssets|toShares)\w*/],
    ['Access-control signals', /\bonlyOwner\b|\bonlyAdmin\b|\bonlyRole\b|require\s*\(\s*msg\.sender/],
    ['Paired function names', /function\s+(?:deposit|withdraw|mint|burn|redeem|borrow|repay|stake|unstake|lock|unlock|open|close|join|exit)\b/],
];

function matchingLines(file, regex) {
    const text = fs.readFileSync(file, 'utf8');
    const hits = [];
    text.split(/\r?\n/).forEach((line, index) => {
        if (regex.test(line)) hits.push({ line: index + 1, text: line });
        regex.lastIndex = 0;
    });
    return hits;
}

function parseArgs(argv) {
    const args = { metaDir: 'fizz_data', suiteDir: 'test/fizz' };
    const positional = [];
    for (let i = 0; i < argv.length; i++) {
        const token = argv[i];
        if (token === '--meta-dir') args.metaDir = argv[++i];
        else if (token === '--suite-dir') args.suiteDir = argv[++i];
        else positional.push(token);
    }
    if (positional.length !== 1) {
        console.error('usage: node build_invariant_context.js <PROJECT_ROOT> [--meta-dir dir] [--suite-dir dir]');
        process.exit(2);
    }
    args.projectRoot = path.resolve(positional[0]);
    return args;
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const protocol = [];
    for (const root of protocolRoots(args.projectRoot)) walkSol(root, protocol);
    const harness = harnessFiles(args.projectRoot, args.suiteDir);
    const seen = new Set();
    const files = [];
    for (const file of [...protocol, ...harness]) {
        const name = rel(args.projectRoot, file);
        if (seen.has(name)) continue;
        seen.add(name);
        files.push(file);
    }
    files.sort((a, b) => rel(args.projectRoot, a).localeCompare(rel(args.projectRoot, b)));

    const metaDir = path.join(args.projectRoot, args.metaDir);
    fs.mkdirSync(metaDir, { recursive: true });
    const listPath = path.join(metaDir, 'scope-files.txt');
    const list = files.map((file) => rel(args.projectRoot, file)).join('\n') + (files.length ? '\n' : '');
    fs.writeFileSync(listPath, list);

    const sections = [];
    sections.push('# Invariant context');
    sections.push('');
    sections.push('Generated by `build_invariant_context.js`. Every matching line is included.');
    sections.push('Discovery agents read the files named in `scope-files.txt`. This file does not replace those reads.');
    sections.push('');
    sections.push('## Scope files');
    sections.push('');
    if (!files.length) sections.push('_No Solidity files matched._');
    for (const file of files) {
        const text = fs.readFileSync(file, 'utf8');
        const lines = text.split(/\r?\n/).length;
        sections.push(`- \`${rel(args.projectRoot, file)}\` — ${lines} lines, ${Buffer.byteLength(text)} bytes`);
    }
    sections.push('');
    const xray = path.join(args.projectRoot, 'x-ray');
    sections.push('## Existing notes');
    sections.push('');
    const notes = [];
    if (fs.existsSync(path.join(xray, 'x-ray.md'))) {
        for (const name of ['x-ray.md', 'invariants.md', 'entry-points.md']) {
            if (fs.existsSync(path.join(xray, name))) notes.push(`x-ray/${name}`);
        }
    }
    const extra = path.join(metaDir, 'additional-context.md');
    const understanding = path.join(metaDir, 'protocol-understanding.md');
    if (fs.existsSync(extra)) notes.push(path.relative(args.projectRoot, extra).split(path.sep).join('/'));
    if (fs.existsSync(understanding)) notes.push(path.relative(args.projectRoot, understanding).split(path.sep).join('/'));
    if (notes.length) {
        sections.push('Read these files for protocol notes. Do not expect them to be pasted here.');
        for (const name of notes) sections.push(`- \`${name}\``);
    } else {
        sections.push('_No x-ray notes and no protocol-understanding.md. Use the source files._');
    }
    sections.push('');

    for (const [title, regex] of PATTERNS) {
        sections.push(`## ${title}`);
        sections.push('');
        let count = 0;
        for (const file of files) {
            const hits = matchingLines(file, regex);
            for (const hit of hits) {
                count += 1;
                sections.push(`- \`${rel(args.projectRoot, file)}:${hit.line}\`: \`${hit.text.trim()}\``);
            }
        }
        if (!count) sections.push('_None._');
        sections.push('');
    }

    const contextPath = path.join(metaDir, 'invariant-context.md');
    fs.writeFileSync(contextPath, sections.join('\n'));
    console.log(`wrote ${rel(args.projectRoot, contextPath)} (${files.length} files)`);
    console.log(`wrote ${rel(args.projectRoot, listPath)}`);
}

main();
